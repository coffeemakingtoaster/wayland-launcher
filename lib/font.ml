(* ASCII range covered by the atlas *)
let first_char = 32
let last_char = 126
let glyph_w = 8
let glyph_h = 8

(* One-pixel horizontal spacing between characters. *)
let char_advance = glyph_w + 1

type t = { texture : Sdl.texture }

let create (renderer : Sdl.renderer) : (t, string) result =
  match
    Sdl.create_rgb_surface_with_format
      ~w:((last_char - first_char + 1) * glyph_w)
      ~h:glyph_h ~depth:32 Sdl.Pixel.format_argb8888
  with
  | Error (`Msg e) -> Error e
  | Ok surface -> (
      (* Paint glyph pixels opaque white on transparent black. *)
      let pixels = Sdl.get_surface_pixels surface Bigarray.int32 in
      let atlas_w = (last_char - first_char + 1) * glyph_w in
      Array.iteri
        (fun idx glyph ->
          let base_x = (idx + first_char - 32) * glyph_w in
          let base_y = 0 in
          Array.iteri
            (fun row line ->
              String.iteri
                (fun col c ->
                  if c = '#' then
                    Bigarray.Array1.set pixels
                      (((base_y + row) * atlas_w) + base_x + col)
                      0xFFFFFFFFl)
                line)
            glyph)
        glyphs;
      match Sdl.create_texture_from_surface renderer surface with
      | Error (`Msg e) ->
          Sdl.free_surface surface;
          Error e
      | Ok texture ->
          Sdl.free_surface surface;
          Ok { texture })

let destroy (t : t) : unit = Sdl.destroy_texture t.texture

(* Draw [text] with top-left corner at ([x], [y]) in pixels, using
   renderer scale 1. For debug rendering. *)
let draw_text (t : t) (renderer : Sdl.renderer) ~x ~y (text : string) : unit =
  let src = Sdl.Rect.create ~x:0 ~y:0 ~w:glyph_w ~h:glyph_h in
  let dst = Sdl.Rect.create ~x ~y ~w:glyph_w ~h:glyph_h in
  String.iteri
    (fun i c ->
      let idx = Char.code c in
      if idx >= first_char && idx <= last_char then begin
        Sdl.Rect.set_x src ((idx - first_char) * glyph_w);
        Sdl.Rect.set_x dst (x + (i * char_advance));
        Sdl.render_copy ~src ~dst renderer t.texture |> Result.is_error
        |> fun _ -> ()
      end)
    text

(* Draw with a text color (RGB, 0-255 each). *)
let draw_text_color (t : t) (renderer : Sdl.renderer) ~x ~y ~r ~g ~b
    (text : string) : unit =
  let _ : bool = Result.is_error (Sdl.set_texture_color_mod t.texture r g b) in
  draw_text t renderer ~x ~y text
